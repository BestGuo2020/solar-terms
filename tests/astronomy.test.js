test('2000–2100 and ancient/distant samples solve ordered events with correct longitude and boundaries',()=>{
  const years=[-1999,-104,0,1,99,100,1600,1700,1900,...Array.from({length:101},(_,i)=>2000+i),2200,2400,2999,3000];
  for(const y of years) {
    const events=yearEvents(y);assert.equal(events.length,24);
    const [a,b]=yearBounds(y);
    events.forEach((e,i)=>{
      assert.ok(e.time>=a&&e.time<b);
      const error=((solarLongitude(e.time)-e.longitude+540)%360)-180;
      assert.ok(Math.abs(error)<1e-6,`${y} ${e.name} longitude residual ${error}`);
      assert.equal(intervalAt(e.time).current.id,e.id);
      assert.equal(intervalAt(e.time+1000).current.id,e.id);
      assert.equal(intervalAt(e.time-1000).next.id,e.id);
      assert.notEqual(intervalAt(e.time-1000).current.id,e.id);
      if(i)assert.ok(e.time>events[i-1].time);
    });
  }
});

// Independent published minute tables, not generated by our solver.
// HKO: https://www.hko.gov.hk/en/gts/astron2025/files/2025SolarTerms24.pdf
// HKO: https://www.hko.gov.hk/en/gts/astron2026/files/2026SolarTerms24.pdf
const hko={
  2025:['01-20T04:00','02-18T18:07','03-20T17:01','04-20T03:56','05-21T02:55','06-21T10:42','07-22T21:29','08-23T04:34','09-23T02:19','10-23T11:51','11-22T09:36','12-21T23:03'],
  2026:['01-20T09:45','02-18T23:52','03-20T22:46','04-20T09:39','05-21T08:37','06-21T16:25','07-23T03:13','08-23T10:19','09-23T08:05','10-23T17:38','11-22T15:23','12-22T04:50'],
};
test('24 independent HKO 2025/2026 major-term fixtures differ by less than one minute',t=>{
  let max=0;
  for(const [year,dates] of Object.entries(hko)) dates.forEach((date,i)=>{
    const longitude=(300+i*30)%360;
    const e=yearEvents(Number(year)).find(e=>e.longitude===longitude);
    const error=Math.abs(e.time-Date.parse(`${year}-${date}:00+08:00`))/1000;
    max=Math.max(max,error);assert.ok(error<60,`${year} ${e.name}: ${error}s`);
  });
  t.diagnostic(`maximum difference against published minutes: ${max.toFixed(3)} seconds`);
});

test('fixed axis faces sunlight in June and away in December; equinox light is perpendicular',()=>{
  const dot=(a,b)=>a.reduce((sum,v,i)=>sum+v*b[i],0);
  for(const longitude of [0,90,180,270]) {
    const e=yearEvents(2026).find(t=>t.longitude===longitude);
    const s=earthState(e.time),len=Math.hypot(...s.position);
    const toSun=s.position.map(v=>-v/len);
    const expected=Math.sin(23.44*Math.PI/180)*Math.sin(longitude*Math.PI/180);
    assert.ok(Math.abs(dot(NORTH_AXIS,toSun)-expected)<1e-7);
    assert.ok(Math.abs(s.declination-(longitude===90?23.44:longitude===270?-23.44:0))<1e-6);
  }
});

