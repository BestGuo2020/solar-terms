test('playback, seeking, today, year crossing and independent spin use one clock',()=>{
  const start=Date.parse('2026-12-31T15:59:59Z'),clock=new SimulationClock(start);
  clock.daysPerSecond=1;clock.togglePlay();clock.tick(1);
  assert.equal(datetimeInput(clock.time).slice(0,10),'2027-01-01');
  assert.ok(!clock.live&&clock.playing);
  const event=yearEvents(2027).find(e=>e.name==='春分');clock.seek(event.time);
  assert.equal(clock.time,event.time);assert.equal(clock.playing,false);
  const angle=clock.spinAngle;clock.tick(1);assert.equal(clock.time,event.time);assert.notEqual(clock.spinAngle,angle);
  clock.spin=false;const frozen=clock.spinAngle;clock.tick(2);assert.equal(clock.spinAngle,frozen);
  clock.today(start);clock.tick(1,start+1000);assert.equal(clock.time,start+1000);assert.ok(clock.live);
  clock.seek(MAX_TIME-1000);clock.togglePlay();clock.tick(1);assert.equal(clock.time,MAX_TIME-1000);assert.ok(!clock.playing&&clock.boundary);
});

